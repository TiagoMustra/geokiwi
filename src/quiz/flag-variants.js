import countries from '../data/countries.json' with {type:'json'};

const byIso=Object.fromEntries(countries.filter(country=>country.isCountry).map(country=>[country.iso3,country]));
const text=(pt,en)=>({pt,en});
const source=(title,url)=>({title,url});
const artwork=source('flag-icons · National flag SVGs (publisher collection)','https://github.com/lipis/flag-icons/tree/main/flags/4x3');
const countryIds=isos=>isos.map(iso=>{
  if(!byIso[iso])throw Error(`Unsupported flag variant country: ${iso}`);
  return byIso[iso].id;
});
const entity=iso=>{
  const country=byIso[iso];
  return {id:country.id,label:text(country.nome_pt,country.nome_en),aliases:country.aliases.filter(alias=>/[a-z0-9]/i.test(alias.normalize('NFD')))};
};
const base=(slug,inputType,isos,prompt,explanation,sources)=>({
  schemaVersion:1,id:`flagsv-${slug}`,revision:1,inputType,category:'flags',topicId:`flags:${slug}`,
  prompt,explanation,sources,checkedAt:'2026-11-06',countryIds:countryIds(isos),
});
const list=(slug,isos,prompt,explanation,sources=[artwork])=>({
  ...base(slug,'TEXT_MULTIPLE',isos,prompt,explanation,sources),suggestionDomain:'countries',answer:{accepted:isos.map(entity)},
});
const single=(slug,iso,prompt,explanation,sources)=>({
  ...base(slug,'TEXT_SINGLE',[iso],prompt,explanation,[...sources,artwork]),suggestionDomain:'countries',answer:{accepted:[entity(iso)]},
});
const assertion=(slug,iso,value,prompt,explanation,sources)=>({
  ...base(slug,'TRUE_FALSE',[iso],prompt,explanation,sources),answer:{value},
});
const count=(slug,iso,value,unit,prompt,explanation,sources)=>({
  ...base(slug,'NUMBER_EXACT',[iso],prompt,explanation,sources),unit,bounds:{min:0,max:100},
  scoring:{fullCreditError:0,zeroCreditError:Math.max(10,value)},answer:{value,absoluteTolerance:0},
});
